#!/usr/bin/env python3
"""Persist a captured workspace's choice of Dwindle or Scrolling."""
import argparse
import fcntl
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import stat


def valid_selector(selector):
    return (selector.startswith("name:") and len(selector) > 5 and not any(ord(c) < 32 for c in selector)) or (
        selector.isascii() and selector.isdigit() and 1 <= int(selector) <= 2147483647)


def lua_string(value):
    # Selectors contain no control characters. Printable JSON strings are Lua strings.
    return json.dumps(value, ensure_ascii=False)


def fragment(state):
    lines = ["-- Generated by Wizarch layouts.py; toggle with Super+Ctrl+L.\n"]
    for selector in sorted(state):
        if not valid_selector(selector) or state[selector] != "scrolling":
            raise ValueError("Invalid saved workspace layout")
        lines.append(f'hl.workspace_rule({{ workspace = {lua_string(selector)}, layout = "scrolling" }})\n')
    return "".join(lines)


def atomic_write(path, value):
    if path.exists() and path.read_text() == value:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    mode = stat.S_IMODE(path.stat().st_mode) if path.exists() else 0o600
    fd, temporary = tempfile.mkstemp(prefix='.' + path.name + '.', dir=path.parent)
    try:
        with os.fdopen(fd, 'w') as stream:
            stream.write(value)
            stream.flush()
            os.fchmod(stream.fileno(), mode)
            os.fsync(stream.fileno())
        os.replace(temporary, path)
        fd = os.open(path.parent, os.O_RDONLY | os.O_DIRECTORY)
        try: os.fsync(fd)
        finally: os.close(fd)
    finally:
        if os.path.exists(temporary): os.unlink(temporary)


def toggle(selector, config):
    if not valid_selector(selector):
        raise ValueError("Expected a numbered or named normal workspace")
    store = config / "wizarch/workspace-layouts.json"
    store.parent.mkdir(parents=True, exist_ok=True)
    with store.with_suffix(".lock").open("w") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        state = json.loads(store.read_text()) if store.exists() else {}
        fragment(state)  # Validate before applying anything.
        workspaces = json.loads(subprocess.check_output(["hyprctl", "workspaces", "-j"], text=True, timeout=3))
        current = next((w["tiledLayout"] for w in workspaces
                        if ("name:" + w["name"] if selector.startswith("name:") else str(w["id"])) == selector),
                       state.get(selector, "dwindle"))
        layout = "dwindle" if current == "scrolling" else "scrolling"
        code = f'hl.workspace_rule({{ workspace = {lua_string(selector)}, layout = {lua_string(layout)} }})'
        result = subprocess.check_output(["hyprctl", "eval", code], text=True, timeout=3)
        if result.strip() != "ok":
            raise RuntimeError(result.strip())
        if layout == "scrolling":
            state[selector] = layout
        else:
            state.pop(selector, None)
        atomic_write(store, json.dumps(state, ensure_ascii=False, indent=2) + "\n")
        atomic_write(config / "hypr/wizarch-layouts.lua", fragment(state))
        return layout


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=("toggle",))
    parser.add_argument("workspace", help="Workspace selector captured at keypress")
    args = parser.parse_args()
    config = Path(os.environ.get("XDG_CONFIG_HOME", str(Path.home() / ".config")))
    print(json.dumps({"workspace": args.workspace, "layout": toggle(args.workspace, config)}))


if __name__ == "__main__":
    try:
        main()
    except Exception as error:
        print(json.dumps({"error": str(error)}), file=sys.stderr)
        sys.exit(1)
