#!/usr/bin/env python3
"""Nine independent workspace slots on each monitor, preserving existing names."""
import argparse
import fcntl
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import tempfile
import stat

BASE = Path(os.environ.get('XDG_RUNTIME_DIR', f'/run/user/{os.getuid()}'))
KEY = re.sub(r'[^a-zA-Z0-9_-]', '_', os.environ.get('HYPRLAND_INSTANCE_SIGNATURE', 'session'))
STATE = BASE / ('wizarch-workspaces-' + KEY + '.json')
CONFIG = Path(os.environ.get('XDG_CONFIG_HOME', str(Path.home() / '.config')))
STORE = CONFIG / 'wizarch/workspace-monitors.json'
FRAGMENT = CONFIG / 'hypr/wizarch-workspaces.lua'


def query(what):
    return json.loads(subprocess.check_output(['hyprctl', what, '-j'], text=True, timeout=3))


def evaluate(code):
    result = subprocess.run(['hyprctl', 'eval', 'do\n' + code + '\nend'], text=True, capture_output=True, timeout=4)
    if result.returncode or result.stdout.strip() != 'ok':
        raise RuntimeError((result.stdout + result.stderr).strip())


def quote(value):
    if not isinstance(value, str) or any(ord(c) < 32 for c in value):
        raise ValueError('Invalid monitor/workspace name')
    return json.dumps(value, ensure_ascii=False)


def selector(name):
    return name if name.isascii() and name.isdigit() else 'name:' + name


def atomic_write(path, value):
    if path.exists() and path.read_text() == value:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    mode = stat.S_IMODE(path.stat().st_mode) if path.exists() else 0o600
    fd, temporary = tempfile.mkstemp(prefix='.' + path.name + '.', dir=path.parent)
    try:
        with os.fdopen(fd, 'w') as stream:
            stream.write(value)
            stream.flush()
            os.fchmod(stream.fileno(), mode)
            os.fsync(stream.fileno())
        os.replace(temporary, path)
        fd = os.open(path.parent, os.O_RDONLY | os.O_DIRECTORY)
        try: os.fsync(fd)
        finally: os.close(fd)
    finally:
        if os.path.exists(temporary): os.unlink(temporary)


def validate_map(mapping):
    seen = set()
    for monitor, slots in mapping.items():
        quote(monitor)
        if set(slots) != {str(i) for i in range(1, 10)}:
            raise ValueError('Each monitor must have nine slots')
        for name in slots.values():
            quote(name)
            if not name or name.startswith(('special:', '__desktop')) or name in seen:
                raise ValueError('Workspace slots must be unique normal workspaces')
            seen.add(name)


def fragment(mapping):
    validate_map(mapping)
    lines = ['-- Generated by Wizarch workspaces.py: nine independent slots per monitor.\n']
    for monitor, slots in sorted(mapping.items()):
        for slot in range(1, 10):
            lines.append('hl.workspace_rule({ workspace = ' + quote(selector(slots[str(slot)]))
                         + ', monitor = ' + quote(monitor) + ', persistent = true'
                         + (', default = true' if slot == 1 else '') + ' })\n')
    return ''.join(lines)


def ensure_map(state, monitors, workspaces, config):
    store = config / 'wizarch/workspace-monitors.json'
    mapping = json.loads(store.read_text())['map'] if store.exists() else state.get('map', {})
    validate_map(mapping)
    assigned = {name for slots in mapping.values() for name in slots.values()}
    for monitor in monitors:
        name = monitor['name']
        if name in mapping:
            continue
        slots = {str(i): f'wizarch-{i}-{name}' for i in range(1, 10)}
        active = monitor['activeWorkspace']['name']
        if active.startswith('__desktop'):
            active = next((w['name'] for w in workspaces if w.get('monitor') == name
                           and not w['name'].startswith(('special:', '__desktop')) and w['name'] not in assigned), '')
        if active and not active.startswith('special:') and active not in assigned:
            slots['1'] = active
        mapping[name] = slots
        assigned.update(slots.values())
    text = fragment(mapping)
    # Reloads load this same fragment. Apply new mappings once, without focusing
    # any monitor or changing the active workspace/window.
    if state.get('rules_map') != mapping:
        evaluate(text)
        atomic_write(config / 'hypr/wizarch-workspaces.lua', text)
        state['rules_map'] = json.loads(json.dumps(mapping))
    if not store.exists() or json.loads(store.read_text()).get('map') != mapping:
        atomic_write(store, json.dumps({'version': 1, 'map': mapping}, ensure_ascii=False, indent=2) + '\n')
    state['map'] = mapping
    return mapping


def observe(state, monitors, clients):
    per_monitor = state.setdefault('monitors', {})
    for monitor in monitors:
        name = monitor['name']
        slots = state['map'][name]
        previous = per_monitor.get(name)
        current_name = monitor['activeWorkspace']['name']
        current = next((int(slot) for slot, workspace in slots.items() if workspace == current_name),
                       previous['current'] if previous else state.get('current', 1))
        desktop = current_name == '__desktop_' + name
        revision = previous['revision'] if previous else 0
        if previous and previous.get('active') != current_name:
            revision += 1
        occupied = {c['workspace']['name'] for c in clients if c.get('monitor') == monitor['id']}
        used = sorted({current} | {int(slot) for slot, workspace in slots.items() if workspace in occupied})
        per_monitor[name] = dict(current=current, used=used, revision=revision, desktop=desktop, active=current_name)


def target_slot(value, current):
    slot = current % 9 + 1 if value == 'next' else (current - 2) % 9 + 1 if value == 'prev' else int(value)
    if not 1 <= slot <= 9:
        raise ValueError('Workspace must be 1–9')
    return slot


def focus_workspace(monitor, workspace):
    # Both dispatches run synchronously; only this monitor's workspace changes.
    evaluate('local m = hl.get_monitor(' + quote(monitor) + '); if not m then error("Monitor disconnected") end; '
             + 'hl.dispatch(hl.dsp.focus({ monitor = m })); '
             + 'hl.dispatch(hl.dsp.focus({ workspace = ' + quote(selector(workspace)) + ' }))')


def run(action='status', value=None, monitor_name=None, config=CONFIG):
    monitors = query('monitors')
    if not monitors:
        raise RuntimeError('No active monitors')
    state = json.loads(STATE.read_text()) if STATE.exists() else {}
    ensure_map(state, monitors, query('workspaces'), config)
    observe(state, monitors, query('clients'))
    monitor = next((m for m in monitors if m['name'] == monitor_name), None) if monitor_name else next(
        (m for m in monitors if m.get('focused')), monitors[0])
    if monitor is None:
        raise ValueError('Monitor is not connected')
    name = monitor['name']
    local = state['monitors'][name]
    if action in ('switch', 'move'):
        slot = target_slot(value, local['current'])
        workspace = state['map'][name][str(slot)]
        if action == 'switch':
            focus_workspace(name, workspace)
        else:
            window = query('activewindow')
            if not window.get('address') or window.get('monitor') != monitor['id']:
                raise ValueError('No focused window on this monitor')
            # Capture the exact window and recheck monitor ownership in the
            # compositor, avoiding an asynchronous worker moving another app.
            evaluate('local w = hl.get_window(' + quote('address:' + window['address'])
                     + '); local m = hl.get_monitor(' + quote(name) + '); '
                     + 'if not w or not m or not w.monitor or w.monitor.id ~= m.id then error("Window changed monitor") end; '
                     + 'hl.dispatch(hl.dsp.window.move({ window = w, workspace = '
                     + quote(selector(workspace)) + ', follow = false }))')
    elif action == 'desktop':
        focus_workspace(name, state['map'][name][str(local['current'])] if local['desktop'] else '__desktop_' + name)
    elif action not in ('status', 'sync'):
        raise ValueError('Unknown action')
    # Sync is observational: native monitor/window navigation never propagates
    # its local workspace choice to the other monitors.
    monitors = query('monitors')
    observe(state, monitors, query('clients'))
    state['version'] = 2
    for legacy in ('current', 'used', 'revision', 'desktop'):
        state.pop(legacy, None)
    atomic_write(STATE, json.dumps(state, ensure_ascii=False) + '\n')
    return {'monitors': {m['name']: state['monitors'][m['name']] for m in monitors}}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', nargs='?', default='status', choices=('status', 'sync', 'switch', 'move', 'desktop'))
    parser.add_argument('value', nargs='?')
    parser.add_argument('--monitor', help='Explicit monitor for a pill click; otherwise use focused monitor')
    args = parser.parse_args()
    if args.action in ('switch', 'move') and args.value is None:
        parser.error('switch/move requires a slot or next/prev')
    with open(str(STATE) + '.lock', 'w') as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        with (CONFIG / 'wizarch').joinpath('workspace-monitors.lock').open('a') as config_lock:
            fcntl.flock(config_lock, fcntl.LOCK_EX)
            print(json.dumps(run(args.action, args.value, args.monitor), ensure_ascii=False))


if __name__ == '__main__':
    try:
        (CONFIG / 'wizarch').mkdir(parents=True, exist_ok=True)
        main()
    except Exception as error:
        print(json.dumps({'error': str(error)}))
        sys.exit(1)
