#!/usr/bin/env python3
"""Apply the Wizarch gap scale live and persist its Hyprland Lua fragment."""
import fcntl
import json
import os
from pathlib import Path
import stat
import subprocess
import sys
import tempfile


def gaps(percent):
    return max(0, int(5 * percent / 100 + .5)), max(0, int(20 * percent / 100 + .5))


def evaluate(config):
    result = subprocess.run(['hyprctl', 'eval', config], capture_output=True, text=True, timeout=5)
    if result.returncode or result.stdout.strip() != 'ok':
        raise RuntimeError((result.stderr or result.stdout).strip() or 'Hyprland did not apply spacing')


def previous_gaps(option):
    result = subprocess.run(['hyprctl', 'getoption', 'general:' + option, '-j'], capture_output=True, text=True, timeout=5)
    if result.returncode: raise RuntimeError('Could not capture previous spacing')
    values = json.loads(result.stdout)['css'].split()
    if len(values) != 4: raise ValueError('Invalid compositor spacing')
    return '{' + ','.join(f'{side}={int(value)}' for side, value in zip(['top','right','bottom','left'],values)) + '}'


def apply(percent, folder):
    if not 0 <= percent <= 150: raise ValueError('Spacing must be between 0 and 150 percent')
    folder.mkdir(parents=True, exist_ok=True)
    destination = folder / 'wizarch-spacing.lua'
    with (folder / '.wizarch-spacing.lock').open('a') as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        inner, outer = gaps(percent)
        config = f'hl.config({{ general = {{ gaps_in = {inner}, gaps_out = {outer} }} }})'
        rollback = 'hl.config({ general = { gaps_in = ' + previous_gaps('gaps_in') + ', gaps_out = ' + previous_gaps('gaps_out') + ' } })'
        fd, temporary = tempfile.mkstemp(prefix='.wizarch-spacing.', dir=folder)
        attempted = False
        try:
            # Complete all file generation before touching the compositor.
            with os.fdopen(fd, 'w') as stream:
                stream.write('-- Generated by Wizarch window spacing settings.\n' + config + '\n')
                stream.flush()
                os.fchmod(stream.fileno(), stat.S_IMODE(destination.stat().st_mode) if destination.exists() else 0o600)
                os.fsync(stream.fileno())
            attempted = True
            evaluate(config)
            os.replace(temporary, destination)
        except Exception as error:
            if attempted:
                try: evaluate(rollback)
                except Exception as recovery:
                    raise RuntimeError(f'{error}; spacing rollback also failed: {recovery}') from error
            raise
        finally:
            if os.path.exists(temporary): os.unlink(temporary)
        return {'ok': True, 'inner': inner, 'outer': outer}


def main():
    try:
        folder = Path(os.environ.get('XDG_CONFIG_HOME', str(Path.home() / '.config'))) / 'hypr'
        print(json.dumps(apply(int(sys.argv[1]), folder)))
    except (IndexError, KeyError, ValueError, OSError, RuntimeError, subprocess.SubprocessError) as error:
        print(json.dumps({'ok': False, 'error': str(error)}))
        return 1
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
